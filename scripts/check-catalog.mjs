// Validates data/catalog.json: required fields, division refs, unique ids, enums.
// Also checks data/media.json against the fiches/captures on disk.
// Usage: npm run catalog:check
import { readFile, access } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(import.meta.url), "..", "..");
const STATUS = new Set(["prod", "beta", "alpha", "wip", "concept"]);
const errors = [];

const cat = JSON.parse(await readFile(join(ROOT, "data", "catalog.json"), "utf8"));
const divIds = new Set(cat.divisions.map(d => d.id));
const seen = new Set();

for (const d of cat.divisions) {
  if (!d.glyph || [...d.glyph].length !== 1) errors.push(`division ${d.id}: glyph manquant ou > 1 caractère`);
}

for (const p of cat.projects) {
  const where = p.id || p.name || "(sans id)";
  if (!p.id) errors.push(`${where}: id manquant`);
  if (seen.has(p.id)) errors.push(`${where}: id en double`);
  seen.add(p.id);
  if (!p.name) errors.push(`${where}: name manquant`);
  if (!divIds.has(p.division)) errors.push(`${where}: division inconnue "${p.division}"`);
  for (const a of p.also || []) {
    if (!divIds.has(a)) errors.push(`${where}: also → division inconnue "${a}"`);
    if (a === p.division) errors.push(`${where}: also répète la division principale`);
  }
  if (!STATUS.has(p.status)) errors.push(`${where}: status invalide "${p.status}"`);
  if (p.install && p.install.type === "github-release" && !p.install.repo)
    errors.push(`${where}: install.repo manquant`);
  // launch.target: file inside launch.dir, relative, never climbing out of it.
  const target = p.launch && p.launch.target;
  if (target && (/^([a-z]:|[\\/])/i.test(target) || target.split(/[\\/]/).includes("..")))
    errors.push(`${where}: launch.target doit être un chemin relatif à launch.dir`);
}

// data/media.json (generated by scripts/build-filiales.py) must match the files on disk.
let media = {};
try { media = JSON.parse(await readFile(join(ROOT, "data", "media.json"), "utf8")); } catch { /* optional */ }
for (const [id, m] of Object.entries(media)) {
  if (!seen.has(id)) errors.push(`media.json: id inconnu "${id}"`);
  const files = [];
  if (m.fiche) files.push(join(ROOT, "data", "fiches", `${id}.md`));
  for (let n = 1; n <= m.captures; n++) files.push(join(ROOT, "web", "assets", "filiales", `${id}-${n}.webp`));
  if (m.captures) files.push(join(ROOT, "web", "assets", "filiales", `${id}-card.webp`));
  for (const f of files) {
    try { await access(f); } catch { errors.push(`media.json: ${id} → fichier manquant ${f.slice(ROOT.length + 1)} (relancer build-filiales.py)`); }
  }
}

if (errors.length) {
  console.error(`✗ ${errors.length} problème(s) :`);
  errors.forEach(e => console.error("  - " + e));
  process.exit(1);
}
console.log(`✓ catalog.json OK — ${cat.projects.length} projets, ${cat.divisions.length} divisions`);
